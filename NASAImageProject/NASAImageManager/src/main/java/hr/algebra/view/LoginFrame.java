    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = tfUsername.getText().trim();
        String password = new String(pfPassword.getPassword());

        if (username.isBlank() || password.isBlank()) {
            MessageUtils.showInformationMessage("Login", "Please enter username and password.");
            return;
        }

        try {
            Optional<AppUser> user = repository.loginUser(
                    username,
                    PasswordUtils.hashPassword(password)
            );

            if (user.isPresent()) {
                new MainFrame(user.get()).setVisible(true);
                dispose();

            } else {
                MessageUtils.showErrorMessage("Login failed", "Wrong username or password.");
            }

        } catch (Exception ex) {
            Logger.getLogger(LoginFrame.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to login.");
        }
    }//GEN-LAST:event_btnLoginActionPerformed

