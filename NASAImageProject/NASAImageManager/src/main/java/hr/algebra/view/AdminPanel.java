    private void btnUploadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadActionPerformed
        handleGui(true);
        lbStatus.setText("Status: Uploading NASA images...");

        new Thread(() -> {
            try {
                List<NasaImage> nasaImages = NasaImageParser.parse();
                repository.createNasaImages(nasaImages);

                java.awt.EventQueue.invokeLater(() -> {
                    lbStatus.setText("Status: Uploaded " + nasaImages.size() + " NASA images.");
                    MessageUtils.showInformationMessage("Upload", "NASA images uploaded successfully.");
                    handleGui(false);
                });

            } catch (Exception ex) {
                Logger.getLogger(AdminPanel.class.getName()).log(Level.SEVERE, null, ex);

                java.awt.EventQueue.invokeLater(() -> {
                    lbStatus.setText("Status: Upload failed.");
                    MessageUtils.showErrorMessage("Upload error", "Unable to upload NASA images.");
                    handleGui(false);
                });
            }
        }).start();
    }//GEN-LAST:event_btnUploadActionPerformed

    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClearActionPerformed
        if (!MessageUtils.showConfirmDialog(
                "Clear data",
                "Do you really want to delete all NASA data and downloaded images?")) {
            return;
        }

        try {
            repository.clearApplicationData();
            deleteAssets();

            lbStatus.setText("Status: Data and images cleared.");
            MessageUtils.showInformationMessage("Clear data", "Data and downloaded images were deleted.");

        } catch (Exception ex) {
            Logger.getLogger(AdminPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Clear error", "Unable to clear data.");
        }
    }//GEN-LAST:event_btnClearActionPerformed

    private void handleGui(boolean working) {
        btnUpload.setEnabled(!working);
        btnClear.setEnabled(!working);
    }

    private void deleteAssets() throws IOException {
        File assetsDir = new File(ASSETS_DIR);

        if (!assetsDir.exists() || !assetsDir.isDirectory()) {
            return;
        }

        File[] files = assetsDir.listFiles();

        if (files == null) {
            return;
        }

        for (File file : files) {
            if (file.isFile() && !file.getName().startsWith("no_image")) {
                Files.deleteIfExists(file.toPath());
            }
        }
    }


