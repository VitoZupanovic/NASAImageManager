    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String username = tfUsername.getText().trim();
        String password = new String(pfPassword.getPassword());
        String confirmPassword = new String(pfConfirmPassword.getPassword());

        if (username.isBlank() || password.isBlank() || confirmPassword.isBlank()) {
            MessageUtils.showInformationMessage("Register", "Please fill in all fields.");
            return;
        }

        if (!password.equals(confirmPassword)) {
            MessageUtils.showErrorMessage("Register", "Passwords do not match.");
            return;
        }

        try {
            AppUser user = new AppUser(
                    username,
                    PasswordUtils.hashPassword(password),
                    Role.USER
            );

            repository.registerUser(user);

            MessageUtils.showInformationMessage("Register", "User registered successfully.");
            dispose();

        } catch (Exception ex) {
            Logger.getLogger(RegisterDialog.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Register", "Unable to register user. Username may already exist.");
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

